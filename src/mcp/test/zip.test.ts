import assert from 'node:assert/strict';
import { describe, test } from 'node:test';
import type { TestContext } from 'node:test';
import { loadReport } from '../report.ts';
import { DEFAULT_TRACE_LIMITS, getTraceSummary, TraceSummaryOutput } from '../trace-summary.ts';
import type { TraceLimits } from '../trace-summary.ts';
import { makeRepo, snapshotTree } from './helpers.ts';
import { contextOptions, resource, ORIGIN, RESULT_DIR, SPEC_ID, T0, testTrace, traceReport } from './traces.ts';
import { writeZip } from './zipwriter.ts';
import type { ZipEntry, ZipOptions } from './zipwriter.ts';

// Malformed and hostile archives. Every case must end in a structured result (never a thrown
// error, never a hang), read nothing beyond the whitelisted entries and write nothing.

const TRACE = `${RESULT_DIR}/trace.zip`;

const TEST = { name: 'test.trace', data: testTrace([]) };
const CONTEXT = { name: '1-trace.trace', data: JSON.stringify(contextOptions('chromium', T0 + 90)) + '\n' };
const NETWORK = { name: '1-trace.network', data: JSON.stringify(resource({ url: `${ORIGIN}/api/profile`, status: 500, start: T0 + 200 })) + '\n' };
const valid = (): ZipEntry[] => [TEST, CONTEXT, NETWORK];

async function run(t: TestContext, archive: Buffer, archiveLimits: Partial<TraceLimits['archive']> = {}): Promise<TraceSummaryOutput> {
  const root = await makeRepo(t, { raw: traceReport([{ status: 'failed', trace: TRACE }]), files: { [TRACE]: archive } });
  const before = await snapshotTree(root);
  const loaded = await loadReport(root);
  const out = await getTraceSummary(loaded, `${SPEC_ID}@${loaded.fingerprint}`, 0, { limits: { ...DEFAULT_TRACE_LIMITS, archive: { ...DEFAULT_TRACE_LIMITS.archive, ...archiveLimits } } });
  assert.deepEqual(TraceSummaryOutput.parse(out), out);
  assert.deepEqual(await snapshotTree(root), before, 'nothing is extracted or written');
  return out;
}

const zip = (entries: ZipEntry[], options?: ZipOptions) => writeZip(entries, options);
const codes = (out: TraceSummaryOutput) => out.trace.reasons.map((r) => r.code);
const entry = (out: TraceSummaryOutput, name: string) => out.coverage?.entries.find((e) => e.name === name);

describe('archive-level problems: unsupported, nothing read', () => {
  const cases: [string, () => Buffer, string][] = [
    ['not a ZIP', () => Buffer.from('definitely not a zip archive, just text'), 'not_zip'],
    ['empty file', () => Buffer.alloc(0), 'not_zip'],
    ['truncated end of central directory', () => zip(valid()).subarray(0, zip(valid()).length - 10), 'not_zip'],
    ['central directory offset out of range', () => zip(valid(), { cdOffset: 10_000_000 }), 'archive_invalid'],
    // Without ZIP64 records yauzl takes the 0xffff marker literally; the entry-count limit refuses it.
    ['ZIP64 entry-count marker without ZIP64 records', () => zip(valid(), { entryCount: 0xffff }), 'too_many_entries'],
    ['traversal name ../1-trace.network', () => zip([...valid(), { name: '../1-trace.network', data: 'x' }]), 'invalid_entry_name'],
    ['backslash name', () => zip([...valid(), { name: 'a\\b', data: 'x' }]), 'invalid_entry_name'],
    ['absolute name', () => zip([...valid(), { name: '/etc/passwd', data: 'x' }]), 'invalid_entry_name'],
    ['drive-letter name', () => zip([...valid(), { name: 'C:x', data: 'x' }]), 'invalid_entry_name'],
    ['NUL in a name', () => zip([...valid(), { name: 'x', rawName: Buffer.from('a\u0000b'), data: 'x' }]), 'invalid_entry_name'],
    ['control character in a name', () => zip([...valid(), { name: 'x', rawName: Buffer.from('res\u0007ources'), data: 'x' }]), 'invalid_entry_name'],
    ['duplicate whitelisted name', () => zip([...valid(), { name: '1-trace.network', data: 'shadow' }]), 'duplicate_entry_name'],
    ['duplicate non-whitelisted name', () => zip([...valid(), { name: 'resources/a', data: '1' }, { name: 'resources/a', data: '2' }]), 'duplicate_entry_name'],
  ];
  for (const [name, make, code] of cases) {
    test(name, async (t) => {
      const out = await run(t, make());
      assert.equal(out.trace.status, 'unsupported');
      assert.deepEqual(codes(out), [code]);
      assert.equal(out.network, null);
      assert.equal(out.coverage, null);
    });
  }

  test('more entries than the limit', async (t) => {
    const many = [...valid(), ...Array.from({ length: 10 }, (_, i) => ({ name: `resources/${i}`, data: '' }))];
    const out = await run(t, zip(many), { maxEntries: 12 });
    assert.equal(out.trace.status, 'unsupported');
    assert.deepEqual(codes(out), ['too_many_entries']);
  });

  test('archive comment before the end record is fine', async (t) => {
    const out = await run(t, zip(valid(), { comment: 'generated by a tool' }));
    assert.equal(out.trace.status, 'ok');
  });
});

describe('entry-level problems: partial, the bad entry contributes nothing', () => {
  test('local header name differs from the central directory name', async (t) => {
    const out = await run(t, zip([TEST, CONTEXT, { ...NETWORK, localName: '1-trace.netw0rk' }]));
    assert.equal(out.trace.status, 'partial');
    assert.deepEqual(entry(out, '1-trace.network'), { name: '1-trace.network', status: 'corrupt', problem: 'local_header_mismatch', lines: 0, skippedLines: 0, crcVerified: false });
    assert.ok(codes(out).includes('entry_local_header_mismatch'));
    assert.equal(out.network?.total, 0);
    assert.equal(out.coverage?.countsAreLowerBounds, true);
  });

  test('CRC mismatch: lines were parsed but the entry is discarded', async (t) => {
    const out = await run(t, zip([TEST, CONTEXT, { ...NETWORK, crc: 0x12345678 }]));
    assert.equal(entry(out, '1-trace.network')?.status, 'corrupt');
    assert.ok(codes(out).includes('entry_crc_mismatch'));
    assert.equal(out.network?.total, 0, 'records from a corrupt entry are never evidence');
  });

  test('declared size smaller or larger than the data', async (t) => {
    const smaller = await run(t, zip([TEST, CONTEXT, { ...NETWORK, declaredSize: 10 }]));
    assert.ok(codes(smaller).includes('entry_size_mismatch'));
    assert.equal(smaller.network?.total, 0);
    const larger = await run(t, zip([TEST, CONTEXT, { ...NETWORK, declaredSize: 100_000 }]));
    assert.ok(codes(larger).includes('entry_size_mismatch'));
  });

  test('ZIP64 size sentinel without a ZIP64 extra field: the short stream is a size mismatch', async (t) => {
    const out = await run(t, zip([TEST, CONTEXT, { ...NETWORK, declaredSize: 0xffffffff }]));
    assert.equal(out.trace.status, 'partial');
    assert.deepEqual(entry(out, '1-trace.network')?.problem, 'size_mismatch');
    assert.equal(out.network?.total, 0);
  });

  test('encrypted entry and unsupported compression method', async (t) => {
    const encrypted = await run(t, zip([TEST, CONTEXT, { ...NETWORK, flags: 1 }]));
    assert.equal(entry(encrypted, '1-trace.network')?.status, 'unsupported');
    assert.ok(codes(encrypted).includes('entry_encrypted'));
    const method = await run(t, zip([TEST, CONTEXT, { ...NETWORK, method: 12 }]));
    assert.ok(codes(method).includes('entry_compression_method'));
  });

  test('corrupt deflate data', async (t) => {
    const archive = zip(valid());
    // Flip bytes inside the first entry's compressed data (after its 30-byte header and name).
    for (let i = 45; i < 60; i++) archive[i] = archive[i]! ^ 0xff;
    const out = await run(t, archive);
    const test = entry(out, 'test.trace');
    assert.equal(test?.status, 'corrupt');
    assert.ok(['inflate_error', 'crc_mismatch', 'size_mismatch'].includes(test!.problem!));
  });

  test('symlink entries are never followed: nothing is extracted, data is read as bytes or ignored', async (t) => {
    const out = await run(t, zip([...valid(), { name: 'resources/link', data: '/etc/passwd', mode: 0o120777 }]));
    assert.equal(out.trace.status, 'ok');
    assert.equal(out.coverage?.unreadEntries, 1);
  });
});

describe('decompression bombs and budgets', () => {
  test('honest-header bomb over the per-entry limit: inflation stops at the limit', async (t) => {
    const out = await run(t, zip([TEST, CONTEXT, { name: '1-trace.network', data: Buffer.alloc(8 * 1024 * 1024) }]), { maxEntryBytes: 1024 * 1024 });
    assert.deepEqual(entry(out, '1-trace.network'), { name: '1-trace.network', status: 'partial', problem: 'declared_size', lines: 0, skippedLines: 0, crcVerified: false });
    assert.ok(codes(out).includes('entry_over_size_limit'));
    assert.ok(out.coverage!.bytesInflated <= 1024 * 1024 + 64 * 1024, `inflated ${out.coverage!.bytesInflated} bytes`);
  });

  test('a large entry over the per-entry limit still yields the evidence before the cut; later entries are read', async (t) => {
    const records = Array.from({ length: 400 }, (_, i) => JSON.stringify(resource({ url: `${ORIGIN}/api/item/${i}`, status: 500, start: T0 + 200 + i })) + '\n').join('');
    const out = await run(t, zip([TEST, CONTEXT, { name: '1-trace.network', data: records }, { name: '2-trace.trace', data: JSON.stringify(contextOptions('', T0 + 95)) + '\n' }]), { maxEntryBytes: 100 * 1024 });
    const network = entry(out, '1-trace.network')!;
    assert.deepEqual([network.status, network.problem, network.crcVerified], ['partial', 'declared_size', false]);
    assert.ok(out.network!.total > 0 && out.network!.total < 400, `read ${out.network!.total} of 400 records`);
    assert.equal(out.coverage?.readUntilMs, 200 + out.network!.total - 1);
    assert.equal(out.coverage?.countsAreLowerBounds, true);
    assert.equal(entry(out, '2-trace.trace')?.status, 'complete', 'the per-entry limit does not stop the scan');
  });

  test('lying header: inflation stops at the declared size', async (t) => {
    const out = await run(t, zip([TEST, CONTEXT, { name: '1-trace.network', data: Buffer.alloc(16 * 1024 * 1024), declaredSize: 100 }]));
    assert.equal(entry(out, '1-trace.network')?.status, 'corrupt');
    assert.ok(codes(out).includes('entry_size_mismatch'));
    assert.ok(out.coverage!.bytesInflated < 64 * 1024, `inflated ${out.coverage!.bytesInflated} bytes`);
  });

  test('many entries under the per-entry limit stop at the total budget', async (t) => {
    const line = JSON.stringify(resource({ url: `${ORIGIN}/a`, start: T0 + 200 })) + '\n';
    const big = line.repeat(Math.ceil((600 * 1024) / line.length));
    const entries = [TEST, CONTEXT, ...[1, 2, 3, 4].map((i) => ({ name: `${i}-trace.network`, data: big }))];
    const out = await run(t, zip(entries), { maxTotalBytes: 1024 * 1024 });
    assert.equal(out.trace.status, 'partial');
    assert.ok(codes(out).includes('byte_budget'));
    assert.ok(out.coverage!.bytesInflated <= 1024 * 1024);
    assert.ok(out.coverage!.entries.some((e) => e.status === 'skipped' && e.problem === 'byte_budget'));
  });

  test('a line longer than the limit is dropped without being buffered whole', async (t) => {
    const huge = 'x'.repeat(3 * 1024 * 1024);
    const out = await run(t, zip([TEST, CONTEXT, { name: '1-trace.network', data: `${huge}\n${NETWORK.data}` }]), { maxLineBytes: 64 * 1024 });
    assert.equal(entry(out, '1-trace.network')?.skippedLines, 1);
    assert.equal(out.network?.total, 1, 'the next line is still read');
  });
});
